import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {createDatabase, asUser, seedWater, USERS} = createRequire(import.meta.url)('../scripts/preview-water.cjs');

test('rodízio da água tem membros, solicitações e rodadas independentes do café', async () => {
  const db = await createDatabase();
  const read = async () => (await db.query('SELECT public.coffee_water_read() AS data')).rows[0].data;
  const requestId = '50000000-0000-0000-0000-000000000001';
  try {
    await seedWater(db);
    await asUser(db);
    let result = await read();
    assert.equal(result.queue.length, 3);
    assert.equal(result.bottles, 3);
    assert.equal(result.liters, 60);
    assert.deepEqual(result.queue.map(item => item.name), [USERS.livia.name, USERS.bruno.name, USERS.ana.name]);
    assert.equal(result.profiles.length, 0);
    assert.equal(result.requests.length, 0);
    assert.ok(result.queue.every(item => item.id === null));
    await assert.rejects(db.query('SELECT * FROM coffee_private.water_history'), /permission denied/);
    await asUser(db, 'bia');
    assert.equal((await read()).me.is_member, false);
    await assert.rejects(db.query("SELECT public.coffee_water_submit($1,1,'Teste')", [requestId]), /incluir você/);
    await assert.rejects(db.query('SELECT public.coffee_water_member_set($1,true,5)', [USERS.bia.id]), /exclusivo/);
    await asUser(db, 'ana');
    await db.query("SELECT public.coffee_water_submit($1,2,'Mais dois garrafões')", [requestId]);
    await db.query("SELECT public.coffee_water_submit($1,2,'Mais dois garrafões')", [requestId]);
    assert.equal((await read()).requests.length, 1);
    await assert.rejects(db.query("SELECT public.coffee_water_submit($1,3,'Mudou')", [requestId]), /indisponível/);
    await assert.rejects(db.query('SELECT public.coffee_water_review($1,true,5)', [requestId]), /exclusivo/);
    await asUser(db, 'admin');
    const coffeeBefore = (await db.query('SELECT public.coffee_read() AS data')).rows[0].data;
    await assert.rejects(db.query('SELECT public.coffee_water_review($1,true,0)', [requestId]), /mudou/);
    await db.query('SELECT public.coffee_water_review($1,true,5)', [requestId]);
    await db.query('SELECT public.coffee_water_review($1,true,5)', [requestId]);
    result = await read();
    assert.equal(result.bottles, 5);
    assert.equal(result.liters, 100);
    assert.equal(result.queue.at(-1).rounds, 4);
    assert.equal(result.version, 6);
    await asUser(db, 'ana');
    await db.query("SELECT public.coffee_water_submit($1,2,'Mais dois garrafões')", [requestId]);
    await asUser(db, 'admin');
    await db.query('SELECT public.coffee_water_member_set($1,false,6)', [USERS.ana.id]);
    await asUser(db, 'ana');
    assert.equal((await read()).me.is_member, false);
    await assert.rejects(db.query("SELECT public.coffee_water_submit(gen_random_uuid(),1,'Teste')"), /incluir você/);
    await asUser(db, 'admin');
    await db.query('SELECT public.coffee_water_member_set($1,true,7)', [USERS.ana.id]);
    assert.equal((await read()).queue.find(item => item.id === USERS.ana.id).rounds, 4);
    assert.deepEqual((await db.query('SELECT public.coffee_read() AS data')).rows[0].data, coffeeBefore);
    await db.query("SELECT public.coffee_user_delete($1,'EXCLUIR')", [USERS.ana.id]);
    result = await read();
    assert.equal(result.queue.length, 2);
    assert.equal(result.bottles, 5);
    assert.ok(result.history.some(item => item.name === USERS.ana.name));
  } finally { await db.close(); }
});
